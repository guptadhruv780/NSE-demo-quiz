function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * Returns `count` questions for a tier with shuffled options.
 * Correct answer tracked via `correctIndex` after shuffle.
 */
export function getMockQuestions(tier = "medium", count = 20) {
  const pool = BANK[tier] || BANK.medium;
  const selected = shuffle(pool).slice(0, Math.min(count, pool.length));

  return selected.map((q) => {
    const indexed = q.options.map((text, i) => ({ text, isCorrect: i === q.correctIndex }));
    const shuffled = shuffle(indexed);
    return {
      id: q.id,
      text: q.text,
      options: shuffled.map((o) => o.text),
      correctIndex: shuffled.findIndex((o) => o.isCorrect),
    };
  });
}

